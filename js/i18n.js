const I18n = (function(){
  const ATTRS = ['alt','aria-label','title'];
  const nodes = [], els = [];
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, { acceptNode: n => n.parentElement.closest('script,style,svg') ? NodeFilter.FILTER_REJECT : (EN[n.nodeValue.trim()] ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_SKIP) });
  while (walk.nextNode()) nodes.push({ n: walk.currentNode, pt: walk.currentNode.nodeValue });
  document.querySelectorAll(ATTRS.map(a => `[${a}]`).join(',')).forEach(el => ATTRS.forEach(a => { const v = el.getAttribute(a); if (v && EN[v]) els.push({ el, a, pt: v }); }));
  const meta = document.querySelector('meta[name="description"]'), metaPt = meta.content, titlePt = document.title;
  const mails = [...document.querySelectorAll('a[href^="mailto:"]')].map(a => ({ a, pt: a.getAttribute('href') }));
  const was = [...document.querySelectorAll('a[data-wa]')].map(a => ({ a, pt: a.getAttribute('href') }));
  let cur = 'pt';
  function set(l){
    cur = l;
    const en = l === 'en';
    nodes.forEach(({ n, pt }) => { const k = pt.trim(); n.nodeValue = en ? pt.replace(k, EN[k]) : pt; });
    els.forEach(({ el, a, pt }) => el.setAttribute(a, en ? EN[pt] : pt));
    document.documentElement.lang = en ? 'en' : 'pt-BR';
    document.title = en ? EN[titlePt] : titlePt; meta.content = en ? EN[metaPt] : metaPt;
    mails.forEach(({ a, pt }) => a.setAttribute('href', en ? pt.replace('Projeto%20de%20motion', 'Motion%20project') : pt));
    was.forEach(({ a, pt }) => a.setAttribute('href', en ? pt.split('?')[0] + '?text=' + encodeURIComponent("Hi Joalyson! I saw your portfolio and I'd like to talk about a project.") : pt));
    try { localStorage.setItem('jb-lang', l); } catch (e) {}
    document.dispatchEvent(new CustomEvent('langchange', { detail:l }));
  }
  return { set, get: () => cur };
})();

/* the toggle: the red loop is redrawn around whichever language is active */
(function(){
  const box = document.getElementById('lang'), loop = document.getElementById('loop'), path = loop.querySelector('path');
  const btns = [...box.querySelectorAll('button')];
  const reduce = matchMedia('(prefers-reduced-motion: reduce)').matches;
  function moveLoop(l, draw){
    const b = btns.find(x => x.dataset.l === l), r = b.getBoundingClientRect(), br = box.getBoundingClientRect();
    loop.style.width = (r.width + 14) + 'px'; loop.style.height = (r.height + 4) + 'px';
    loop.style.transform = `translate(${r.left - br.left - 7}px, ${r.top - br.top - 2}px) rotate(${l === 'en' ? 4 : -3}deg)`;
    if (draw && window.gsap && !reduce) gsap.fromTo(path, { strokeDasharray:1, strokeDashoffset:1 }, { strokeDashoffset:0, duration:.6, ease:'power2.inOut', delay:.1 });
  }
  function choose(l, draw){
    btns.forEach(b => b.setAttribute('aria-pressed', b.dataset.l === l));
    if (l !== I18n.get()) I18n.set(l);
    moveLoop(l, draw);
    if (draw && window.gsap && !reduce) gsap.fromTo('main h2, .hero-foot p, .hello p, .note span, .work-head p, .slist .n, .notecard .ps', { y:8, opacity:0, rotation:() => gsap.utils.random(-2, 2) }, { y:0, opacity:1, rotation:0, duration:.5, ease:'back.out(2)', stagger:.015, overwrite:'auto' });
  }
  btns.forEach(b => b.addEventListener('click', () => choose(b.dataset.l, true)));
  let start = 'pt';
  const q = new URLSearchParams(location.search).get('lang');
  try { start = q === 'en' || q === 'pt' ? q : (localStorage.getItem('jb-lang') || (navigator.language.startsWith('pt') ? 'pt' : 'pt')); } catch (e) {}
  choose(start === 'en' ? 'en' : 'pt', false);
  document.fonts && document.fonts.ready.then(() => moveLoop(I18n.get(), false));
  addEventListener('resize', () => moveLoop(I18n.get(), false));
})();
